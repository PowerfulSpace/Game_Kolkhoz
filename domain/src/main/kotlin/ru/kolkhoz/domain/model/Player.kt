package ru.kolkhoz.domain.model

/**
 * Идентификатор игрока.
 *
 * Выбран `String`, а не `Int`, по следующим причинам:
 * - снаружи (UI/хранилище) естественнее приходить UUID/GUID, а не порядковый номер;
 * - исключает случайную арифметику над id (`id + 1`, сравнение «больше») —
 *   сравнение имеет смысл только по равенству;
 * - безопасно сериализуется в Room/JSON без потери типа.
 *
 * Value class инлайнится в `String` на JVM, поэтому хранение без накладных расходов.
 */
@JvmInline
value class PlayerId(val value: String)

/**
 * Игрок партии.
 *
 * @property id стабильный идентификатор игрока
 * @property name отображаемое имя (должно быть непустым и уникальным в партии)
 * @property position позиция в порядке хода, `0..N-1`; порядок цикла совпадает с порядком списка игроков
 */
data class Player(
    val id: PlayerId,
    val name: String,
    val position: Int,
)
