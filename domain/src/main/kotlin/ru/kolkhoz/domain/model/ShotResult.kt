package ru.kolkhoz.domain.model

/**
 * Результат одного удара.
 *
 * В игре известны ровно два исхода, поэтому используется enum, а не sealed class.
 */
enum class ShotResult {
    /** Шар забит: забивший получает +1, «предыдущий игрок» получает −1. */
    POCKET,

    /** Промах: счёт не меняется, ход переходит следующему по циклу. */
    MISS,
}
